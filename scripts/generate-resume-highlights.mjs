import { mkdir, readFile, writeFile } from "node:fs/promises";

const data = JSON.parse(await readFile("src/generated/portfolio.json", "utf8"));

function latex(value) {
  return String(value)
    .replace(/[…]/g, "...")
    .replace(/[–—]/g, "-")
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/([#$%&_{}])/g, "\\$1")
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}");
}

function href(value) {
  return String(value).replace(/[{}]/g, "");
}

function contributionRows(pullRequests) {
  const groups = new Map();
  for (const pullRequest of pullRequests.slice(0, 8)) {
    if (!groups.has(pullRequest.repository)) groups.set(pullRequest.repository, []);
    groups.get(pullRequest.repository).push(pullRequest);
  }
  return [...groups.entries()].map(([repository, pullRequests]) => {
    const changes = pullRequests
      .map((pullRequest) => `\\href{${href(pullRequest.href)}}{\\#${pullRequest.number}} ${latex(pullRequest.title)}`)
      .join("; ");
    return `\\(\\bullet\\) \\textbf{${latex(repository)}:} ${changes}.`;
  });
}

function projectEntry(project) {
  const projectHref = project.repositoryUrl || project.liveUrl || project.href;
  const stack = project.technologies.join(", ");
  const approach = project.resume.approach
    .map((item) => `\\(\\bullet\\) ${latex(item)}`)
    .join("\\newline");
  return `\\entryhead{${latex(project.title)}}{${latex(stack)}}{\\href{${href(projectHref)}}{Project Link}}%
\\noindent\\begin{tabular}{|m{1.8cm}|m{17.1cm}|}
\\hline
\\centering\\textbf{Objective} & ${latex(project.resume.objective)}\\\\
\\hline
\\centering\\textbf{Approach} & ${approach}\\\\
\\hline
\\centering\\textbf{Impact} & ${latex(project.resume.impact)}\\\\
\\hline
\\end{tabular}%`;
}

const contributions = contributionRows(data.pullRequests);
const projects = data.projects.filter((project) => project.resume.include).map(projectEntry);
const projectBreak = projects.length > 4
  ? `${projects.slice(0, 4).join("\n")}
\\newpage
{\\large\\textbf{\\begin{tcolorbox}\\textsc{Key Projects / Open Source Contributions (continued)}\\end{tcolorbox}}}%
${projects.slice(4).join("\n")}`
  : projects.join("\n");
const output = `% Generated by scripts/generate-resume-highlights.mjs. Do not edit manually.
\\entryhead{Open Source Contributions}{}{Various}%
\\noindent\\begin{tabular}{|m{1.8cm}|m{17.1cm}|}
\\hline
\\centering\\textbf{Overview} &
${contributions.join("\\newline\n")}\\\\
\\hline
\\end{tabular}%
${projectBreak}
`;

await mkdir("resume/generated", { recursive: true });
await writeFile("resume/generated/projects-and-contributions.tex", output);
console.log(`Generated résumé section with ${projects.length} projects and ${contributions.length} contribution groups.`);
