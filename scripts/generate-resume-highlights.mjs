import { mkdir, readFile, writeFile } from "node:fs/promises";

const data = JSON.parse(await readFile("src/generated/portfolio.json", "utf8"));

function latex(value) {
  return String(value)
    .replace(/[…]/g, "...")
    .replace(/[–—]/g, "-")
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/([#$%&_{}])/g, "\\$1")
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}");
}

function href(value) {
  return String(value).replace(/[{}]/g, "");
}

function contributionRows(pullRequests) {
  const groups = new Map();
  for (const pullRequest of pullRequests.slice(0, 8)) {
    if (!groups.has(pullRequest.repository)) groups.set(pullRequest.repository, []);
    groups.get(pullRequest.repository).push(pullRequest);
  }
  return [...groups.entries()].map(([repository, pullRequests]) => {
    const changes = pullRequests
      .map((pullRequest) => `\\href{${href(pullRequest.href)}}{\\#${pullRequest.number}} ${latex(pullRequest.title)}`)
      .join("; ");
    return `\\textbullet\\enspace \\textbf{${latex(repository)}:}\\enspace ${changes}.`;
  });
}

function projectEntry(project) {
  const projectHref = project.liveUrl || project.href || project.repositoryUrl;
  const stack = project.technologies.join(", ");
  const approach = project.resume.approach
    .map((item) => `\\textbullet\\enspace ${latex(item)}.`)
    .join(" \\enspace ");
  return `\\noindent\\begin{minipage}{\\linewidth}
\\entryhead{${latex(project.title)}}{${latex(stack)}}{\\href{${href(projectHref)}}{Project Link}}%
\\noindent\\begin{tabular}{|p{\\dimexpr\\linewidth-2\\tabcolsep-2\\arrayrulewidth\\relax}|}
\\hline
\\textbf{Objective:}\\enspace ${latex(project.resume.objective)} \\\\[2pt]
\\textbf{Approach:}\\enspace ${approach} \\\\[2pt]
\\textbf{Impact:}\\enspace ${latex(project.resume.impact)} \\\\
\\hline
\\end{tabular}%
\\end{minipage}\\par`;
}

const contributions = contributionRows(data.pullRequests);
const projects = data.projects.filter((project) => project.resume.include).map(projectEntry);
const contributionContent = contributions.length > 0
  ? contributions.join("\\\\[3pt]\n")
  : "No qualifying merged contributions are currently selected.";

const contributionOutput = `% Generated by scripts/generate-resume-highlights.mjs. Do not edit manually.
\\sectionhead{Open Source Contributions}%
\\noindent\\begin{tabular}{|p{\\dimexpr\\linewidth-2\\tabcolsep-2\\arrayrulewidth\\relax}|}
\\hline
${contributionContent}\\\\
\\hline
\\end{tabular}%
`;

const projectOutput = `% Generated by scripts/generate-resume-highlights.mjs. Do not edit manually.
${projects.length > 0 ? `\\sectionhead{Key Projects}%\n${projects.join("\n")}` : "% No resume projects are currently selected."}
`;

await mkdir("resume/generated", { recursive: true });
await Promise.all([
  writeFile("resume/generated/open-source-contributions.tex", contributionOutput),
  writeFile("resume/generated/projects.tex", projectOutput),
]);
console.log(`Generated résumé section with ${projects.length} projects and ${contributions.length} contribution groups.`);
