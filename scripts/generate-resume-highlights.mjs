import { mkdir, readFile, writeFile } from "node:fs/promises";

const data = JSON.parse(await readFile("src/generated/portfolio.json", "utf8"));

function latex(value) {
  return String(value)
    .replace(/[…]/g, "...")
    .replace(/[–—]/g, "-")
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/([#$%&_{}])/g, "\\$1")
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}");
}

const projects = data.projects.slice(0, 6).map((project) => {
  const href = project.repositoryUrl || project.href;
  const tags = project.technologies.slice(0, 4).join(", ");
  return `\\item \\textbf{\\href{${href}}{${latex(project.title)}}}${tags ? ` (${latex(tags)})` : ""}: ${latex(project.description)}`;
});

const prs = data.pullRequests.slice(0, 8).map((pr) =>
  `\\item \\textbf{\\href{${pr.href}}{${latex(pr.repository)} \\#${pr.number}}}: ${latex(pr.title)} (${pr.stars.toLocaleString("en-US")} stars)`,
);

const output = `% Generated by scripts/generate-resume-highlights.mjs. Do not edit manually.
\\clearpage
{\\large\\textbf{\\begin{tcolorbox}\\textsc{Living Portfolio Highlights}\\end{tcolorbox}}}
\\noindent This appendix is synchronized from the projects and merged upstream contributions shown at \\href{https://sankalpjha.dev}{sankalpjha.dev}. Last generated: ${latex(data.generatedAt.slice(0, 10))}.

\\subsection*{Selected Projects}
\\begin{itemize}[leftmargin=14pt]
${projects.join("\n")}
\\end{itemize}

\\subsection*{Selected Merged Pull Requests}
\\begin{itemize}[leftmargin=14pt]
${prs.length ? prs.join("\n") : "\\item Featured upstream pull requests will appear after the next successful GitHub sync."}
\\end{itemize}
`;

await mkdir("resume/generated", { recursive: true });
await writeFile("resume/generated/portfolio-highlights.tex", output);
console.log("Generated resume/generated/portfolio-highlights.tex");
